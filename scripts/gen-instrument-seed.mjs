// Regenerates the instrument 1.1 seed migration from seed/item_bank_1_1.json (Appendix C).
// Usage: node scripts/gen-instrument-seed.mjs <migration-file>
import { readFileSync, writeFileSync } from "node:fs";

const out = process.argv[2];
if (!out) throw new Error("usage: gen-instrument-seed.mjs <migration-file>");
const bank = JSON.parse(readFileSync(new URL("../seed/item_bank_1_1.json", import.meta.url), "utf8"));

const q = (s) => {
  if (s.includes("$q$")) throw new Error("text contains $q$");
  return `$q$${s}$q$`;
};
const V = "ins_v1_1";

const scen = new Map();
for (const x of bank.scen) {
  const id = `${x.dim}-S${x.s}`;
  const e = scen.get(id) ?? { dim: x.dim, s: x.s, title: x.title, statements: x.statements };
  e[x.persp === "NOW" ? "now" : "pref"] = x.prompt;
  scen.set(id, e);
}

const lines = [
  "-- DRAFT FOR REVIEW. Not applied.",
  "-- 6/6 Seed: instrument 1.1 (Appendix C item bank) and rules 2.0, both published.",
  "-- GENERATED by scripts/gen-instrument-seed.mjs from seed/item_bank_1_1.json. Do not edit by hand.",
  "-- 360 self/rater items (120) are not seeded: Leadership 360 is outside the demo slice.",
  "",
  `insert into public.instrument_version (version_id, semver, status) values ('${V}', '1.1', 'DRAFT');`,
  `insert into public.rules_version (version_id, semver, status, published_at) values ('rul_v2_0', '2.0', 'PUBLISHED', now());`,
  "",
  "insert into public.scenario (version_id, scenario_id, dimension, sequence, title, prompt_now, prompt_preferred) values",
  [...scen].map(([id, e]) => `  ('${V}', '${id}', '${e.dim}', ${e.s}, ${q(e.title)}, ${q(e.now)}, ${q(e.pref)})`).join(",\n") + ";",
  "",
  "insert into public.scenario_statement (version_id, scenario_id, orientation, text) values",
  [...scen].flatMap(([id, e]) => Object.entries(e.statements).map(([o, t]) => `  ('${V}', '${id}', '${o}', ${q(t)})`)).join(",\n") + ";",
  "",
  "insert into public.item (version_id, item_id, block, dimension, sequence, scale_type, title, canonical_text) values",
  [
    ...Object.entries(bank.likert).flatMap(([d, items]) =>
      items.map((t, i) => `  ('${V}', '${d}-${String(i + 1).padStart(2, "0")}', 'LIKERT', '${d}', ${i + 1}, '1-5', null, ${q(t)})`)),
    ...bank.eos.map((t, i) => `  ('${V}', 'EOS-${i + 1}', 'EOS', null, ${i + 1}, '0-10', null, ${q(t)})`),
    ...bank.qual.map((x, i) => `  ('${V}', '${x.code}', 'QUAL', null, ${i + 1}, 'TEXT', ${q(x.title)}, ${q(x.text)})`),
  ].join(",\n") + ";",
  "",
  `update public.instrument_version set status = 'PUBLISHED' where version_id = '${V}';`,
  "",
];
writeFileSync(out, lines.join("\n"));
console.log(`wrote ${out}: ${scen.size} scenarios, ${scen.size * 4} statements`);
